create or replace function public.radio_create_library_playlist(
  p_id uuid,
  p_title text,
  p_description text,
  p_tracks jsonb
)
returns public.radio_library_playlists
language plpgsql
security definer
set search_path = public, storage, pg_temp
as $$
declare
  v_playlist public.radio_library_playlists%rowtype;
  v_track jsonb;
  v_count integer;
  v_position integer;
  v_file_name text;
  v_storage_path text;
  v_file_size bigint;
begin
  if auth.uid() is null or not public.is_hub_admin() then
    raise exception 'RADIO_ADMIN_REQUIRED' using errcode = '42501';
  end if;
  if p_id is null then raise exception 'RADIO_LIBRARY_ID_REQUIRED' using errcode = '22023'; end if;
  if p_title is null or btrim(p_title) = '' then raise exception 'RADIO_LIBRARY_TITLE_REQUIRED' using errcode = '22023'; end if;
  if jsonb_typeof(p_tracks) <> 'array' then raise exception 'RADIO_LIBRARY_TRACKS_REQUIRED' using errcode = '22023'; end if;

  v_count := jsonb_array_length(p_tracks);
  if v_count < 1 or v_count > 30 then raise exception 'RADIO_LIBRARY_TRACK_COUNT_INVALID' using errcode = '22023'; end if;

  insert into public.radio_library_playlists (id, created_by, title, description)
  values (p_id, auth.uid(), left(btrim(p_title), 120), nullif(btrim(p_description), ''))
  returning * into v_playlist;

  for v_track in select value from jsonb_array_elements(p_tracks)
  loop
    v_position := nullif(v_track->>'position', '')::integer;
    v_file_name := nullif(btrim(v_track->>'file_name'), '');
    v_storage_path := nullif(btrim(v_track->>'storage_path'), '');
    v_file_size := nullif(v_track->>'file_size_bytes', '')::bigint;
    if v_position is null or v_position < 1 or v_position > 100 then raise exception 'RADIO_LIBRARY_POSITION_INVALID' using errcode = '22023'; end if;
    if v_file_name is null then raise exception 'RADIO_LIBRARY_FILE_NAME_REQUIRED' using errcode = '22023'; end if;
    if v_storage_path is null or v_storage_path not like ('library/' || p_id::text || '/%') then raise exception 'RADIO_LIBRARY_STORAGE_PATH_INVALID' using errcode = '22023'; end if;
    if not exists (select 1 from storage.objects o where o.bucket_id = 'radio-playlists' and o.name = v_storage_path) then raise exception 'RADIO_LIBRARY_FILE_NOT_FOUND' using errcode = '22023'; end if;
    insert into public.radio_library_tracks (playlist_id, position, file_name, storage_path, file_size_bytes)
    values (p_id, v_position, left(v_file_name,255), v_storage_path, v_file_size);
  end loop;
  return v_playlist;
end;
$$;

