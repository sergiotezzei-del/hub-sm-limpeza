create or replace function public.radio_process_program()
returns integer
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_entry public.radio_program_entries%rowtype;
  v_local timestamp;
  v_due boolean;
  v_run_key text;
  v_session_id uuid;
  v_target_id uuid;
begin
  if exists (select 1 from public.radio_playlist_sessions s where s.status in ('queued','claimed','playing','stop_requested')) then return 0; end if;
  if exists (select 1 from public.radio_runtime_state r where r.id='main' and r.operating_mode='temporary') then return 0; end if;
  for v_entry in select * from public.radio_program_entries p where p.active order by p.created_at
  loop
    v_due := false; v_run_key := null;
    if v_entry.schedule_type='once' then
      if v_entry.run_at <= now() and coalesce(v_entry.last_run_key,'') <> 'once' then v_due := true; v_run_key := 'once'; end if;
    else
      v_local := now() at time zone v_entry.timezone;
      v_run_key := to_char(v_local::date,'YYYY-MM-DD');
      if extract(dow from v_local)::smallint = any(v_entry.weekdays)
         and v_entry.local_time <= v_local::time
         and coalesce(v_entry.last_run_key,'') <> v_run_key then v_due := true; end if;
    end if;
    if v_due then
      v_target_id := case when v_entry.target_type='playlist' then v_entry.playlist_id else v_entry.content_id end;
      begin
        v_session_id := public.radio_launch_persistent_target_internal(v_entry.target_type,v_target_id,'schedule',null);
        update public.radio_program_entries set last_run_key=v_run_key,last_run_at=now(),last_error=null,active=case when schedule_type='once' then false else active end where id=v_entry.id;
        insert into public.radio_program_log(program_id,session_id,status,message) values(v_entry.id,v_session_id,'queued','Programação enviada para a Rádio Santa Maria.');
        return 1;
      exception when others then
        update public.radio_program_entries set last_run_key=v_run_key,last_run_at=now(),last_error=sqlerrm,active=case when schedule_type='once' then false else active end where id=v_entry.id;
        insert into public.radio_program_log(program_id,status,message) values(v_entry.id,'failed',sqlerrm);
        return 0;
      end;
    end if;
  end loop;
  return 0;
end;
$$;

revoke all on function public.radio_process_program() from public, anon, authenticated;

