create or replace function public.radio_reorder_library_playlist(p_playlist_id uuid, p_track_ids uuid[])
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_total integer;
  v_id uuid;
  v_position integer := 0;
begin
  if auth.uid() is null or not public.is_hub_admin() then raise exception 'RADIO_ADMIN_REQUIRED' using errcode='42501'; end if;
  select count(*) into v_total from public.radio_library_tracks where playlist_id=p_playlist_id;
  if v_total <> coalesce(cardinality(p_track_ids),0) then raise exception 'RADIO_LIBRARY_REORDER_INVALID' using errcode='22023'; end if;
  update public.radio_library_tracks set position = position + 1000 where playlist_id=p_playlist_id;
  foreach v_id in array p_track_ids loop
    v_position := v_position + 1;
    update public.radio_library_tracks set position=v_position where playlist_id=p_playlist_id and id=v_id;
    if not found then raise exception 'RADIO_LIBRARY_REORDER_INVALID' using errcode='22023'; end if;
  end loop;
  return true;
end;
$$;

create or replace function public.radio_remove_library_track(p_track_id uuid)
returns text
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_playlist_id uuid;
  v_path text;
begin
  if auth.uid() is null or not public.is_hub_admin() then raise exception 'RADIO_ADMIN_REQUIRED' using errcode='42501'; end if;
  delete from public.radio_library_tracks where id=p_track_id returning playlist_id,storage_path into v_playlist_id,v_path;
  if not found then raise exception 'RADIO_LIBRARY_TRACK_NOT_FOUND' using errcode='P0002'; end if;
  with ranked as (
    select id,row_number() over(order by position,id)::integer as rn from public.radio_library_tracks where playlist_id=v_playlist_id
  )
  update public.radio_library_tracks t set position=ranked.rn+1000 from ranked where t.id=ranked.id;
  update public.radio_library_tracks set position=position-1000 where playlist_id=v_playlist_id;
  return v_path;
end;
$$;

create or replace function public.radio_enter_temporary_mode_internal(p_actor uuid)
returns public.radio_runtime_state
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_runtime public.radio_runtime_state%rowtype;
  v_player public.radio_player_state%rowtype;
