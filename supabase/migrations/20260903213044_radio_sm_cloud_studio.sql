  return v_runtime;
end;
$$;

create or replace function public.radio_launch_persistent_target_internal(p_target_type text, p_target_id uuid, p_triggered_by text, p_actor uuid)
returns uuid
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_session_id uuid := gen_random_uuid();
  v_title text;
  v_track_count integer;
  v_content public.radio_content_items%rowtype;
begin
  if p_target_type not in ('playlist','content') then raise exception 'RADIO_TARGET_INVALID' using errcode='22023'; end if;
  if p_triggered_by not in ('manual','schedule') then raise exception 'RADIO_TRIGGER_INVALID' using errcode='22023'; end if;
  if exists (select 1 from public.radio_playlist_sessions s where s.status in ('queued','claimed','playing','stop_requested')) then raise exception 'RADIO_PLAYLIST_ALREADY_ACTIVE' using errcode='55000'; end if;
  if exists (select 1 from public.radio_runtime_state r where r.id='main' and r.operating_mode='temporary') then raise exception 'RADIO_TEMPORARY_MODE_ALREADY_ACTIVE' using errcode='55000'; end if;
  if p_target_type='playlist' then
    select p.title into v_title from public.radio_library_playlists p where p.id=p_target_id and not p.is_archived;
    if v_title is null then raise exception 'RADIO_LIBRARY_NOT_FOUND' using errcode='P0002'; end if;
    select count(*) into v_track_count from public.radio_library_tracks t where t.playlist_id=p_target_id;
    if v_track_count < 1 then raise exception 'RADIO_LIBRARY_EMPTY' using errcode='55000'; end if;
  else
    select * into v_content from public.radio_content_items c where c.id=p_target_id and c.status='ready';
    if not found or v_content.audio_storage_path is null then raise exception 'RADIO_CONTENT_NOT_READY' using errcode='55000'; end if;
    v_title := v_content.title;
  end if;
  perform public.radio_enter_temporary_mode_internal(p_actor);
  insert into public.radio_playlist_sessions(id,created_by,title,status,source_type,source_id,triggered_by)
  values(v_session_id,p_actor,left(v_title,120),'queued',case when p_target_type='playlist' then 'library_playlist' else 'content_item' end,p_target_id,p_triggered_by);
  if p_target_type='playlist' then
    insert into public.radio_playlist_tracks(session_id,position,file_name,storage_path,cleanup_after_play)
    select v_session_id,t.position,t.file_name,t.storage_path,false from public.radio_library_tracks t where t.playlist_id=p_target_id order by t.position;
    update public.radio_library_playlists set play_count=play_count+1,last_played_at=now() where id=p_target_id;
  else
    insert into public.radio_playlist_tracks(session_id,position,file_name,storage_path,cleanup_after_play)
    values(v_session_id,1,coalesce(v_content.audio_file_name,'conteudo.mp3'),v_content.audio_storage_path,false);
    update public.radio_content_items set play_count=play_count+1,last_played_at=now() where id=p_target_id;
  end if;
  return v_session_id;
end;
$$;

